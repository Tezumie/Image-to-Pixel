// Generates lib/core/dither/bluenoise-data.js: a 64×64 blue-noise threshold map made with
// Ulichney's void-and-cluster method. Deterministic (seeded), so re-running gives the same file.
//   node scripts/gen-bluenoise.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const N = 64, SIGMA = 1.5, n = N * N;
let seed = 0x9e3779b9;
const rand = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);

// toroidal gaussian kernel
const K = new Float64Array(n);
for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
  const dx = Math.min(x, N - x), dy = Math.min(y, N - y);
  K[y * N + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA));
}
function addEnergy(E, idx, sign) {
  const ix = idx % N, iy = (idx / N) | 0;
  for (let y = 0; y < N; y++) {
    const ky = ((y - iy + N) % N) * N;
    for (let x = 0; x < N; x++) E[y * N + x] += sign * K[ky + ((x - ix + N) % N)];
  }
}
const energyOf = pat => { const E = new Float64Array(n); for (let i = 0; i < n; i++) if (pat[i]) addEnergy(E, i, 1); return E; };
const tightest = (pat, E, want) => { let b = -1, bv = -Infinity; for (let i = 0; i < n; i++) if (pat[i] === want && E[i] > bv) { bv = E[i]; b = i; } return b; };
const loosest = (pat, E, want) => { let b = -1, bv = Infinity; for (let i = 0; i < n; i++) if (pat[i] === want && E[i] < bv) { bv = E[i]; b = i; } return b; };

// phase 0: initial pattern, relaxed until stable
const init = new Uint8Array(n);
let ones = 0;
while (ones < n / 10) { const i = (rand() * n) | 0; if (!init[i]) { init[i] = 1; ones++; } }
let E = energyOf(init);
for (let guard = 0; guard < 10000; guard++) {
  const c = tightest(init, E, 1); init[c] = 0; addEnergy(E, c, -1);
  const v = loosest(init, E, 0); init[v] = 1; addEnergy(E, v, 1);
  if (c === v) break;
}

const rank = new Int32Array(n).fill(-1);
// phase 1: rank the initial points
{
  const pat = init.slice(); const E1 = energyOf(pat); let r = ones;
  while (r > 0) { const c = tightest(pat, E1, 1); pat[c] = 0; addEnergy(E1, c, -1); rank[c] = --r; }
}
// phase 2: fill voids up to half
const pat = init.slice(); E = energyOf(pat); let r = ones;
while (r < n / 2) { const v = loosest(pat, E, 0); pat[v] = 1; addEnergy(E, v, 1); rank[v] = r++; }
// phase 3: rank the rest by tightest cluster of the remaining zeros
const Z = new Float64Array(n); for (let i = 0; i < n; i++) if (!pat[i]) addEnergy(Z, i, 1);
while (r < n) { const c = tightest(pat, Z, 0); pat[c] = 1; addEnergy(Z, c, -1); rank[c] = r++; }

const bytes = Uint8Array.from(rank, v => Math.floor(v * 256 / n));
const b64 = Buffer.from(bytes).toString('base64');
const out = `// Generated by scripts/gen-bluenoise.mjs: 64×64 void-and-cluster blue noise, one byte per cell (0..255).
export const BLUE_NOISE_SIZE = ${N};
export const BLUE_NOISE_B64 = '${b64}';
`;
writeFileSync(fileURLToPath(new URL('../lib/core/dither/bluenoise-data.js', import.meta.url)), out);
console.log('bluenoise-data.js written', bytes.length, 'bytes');
